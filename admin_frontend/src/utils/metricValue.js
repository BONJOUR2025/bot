/**
 * Общий механизм подгонки денежного значения под ширину прибора.
 *
 * Раньше жил внутри Kpi.jsx и работал только там. Дашборд рисует свои
 * показатели другой композицией и этой защиты не имел — на 375px
 * «1 042 855» требовало 140px в колонке шириной 112 и обрезалось.
 * Композиции остаются разными, а вот способ показать число — один.
 *
 * Работает в паре с .ui-metric-fit / .ui-metric--kpi в globals.css:
 * шрифт значения моноширинный, ширина символа строго пропорциональна
 * кеглю (замерено: 0.59 × font-size), поэтому CSS способен сам
 * подобрать размер — ему не хватает только длины строки. Её и отдаём
 * через --kpi-len, ширину даёт container query.
 */

/**
 * toLocaleString('ru-RU') разделяет разряды неразрывным пробелом,
 * поэтому «10 577 249 ₽» с точки зрения переноса — одно слово. Когда
 * оно не влезает, браузер рвёт его в произвольном месте: «10 577 2 /
 * 49 ₽» — цифры на месте, но число не прочитать. Заменяем неразрывные
 * пробелы обычными, а перед знаком валюты, наоборот, ставим
 * неразрывный: сумма должна читаться как один объект, и «10 577 249 /
 * ₽» выглядит как ошибка вёрстки.
 */
export function breakableNumber(value) {
  if (typeof value !== 'string') return value;
  return value.replace(/[\u00A0\u202F]/g, ' ').replace(/ (₽|\$|€|%|руб\.?)\s*$/u, '\u00A0$1');
}

/** Длина значения в символах — единственное, чего не хватает CSS. */
export function metricLen(value) {
  return typeof value === 'string' || typeof value === 'number'
    ? String(value).length
    : null;
}
