/**
 * Палитра для серий графиков.
 *
 * Смысл этих цветов — «отличаться друг от друга», а не «означать
 * состояние». Поэтому они заданы литералами, а не семантическими
 * токенами: токенов ровно столько, сколько состояний (успех,
 * предупреждение, ошибка, информация), и при переводе палитр на них
 * восемь различимых оттенков схлопнулись в шесть с двумя парами
 * дублей — два сектора диаграммы становились одного цвета.
 *
 * Оттенки средней светлоты, чтобы читаться и на почти чёрном фоне
 * тёмной темы, и на светло-сером фоне светлой. Порядок подобран так,
 * чтобы соседние по списку серии заметно расходились по тону: на
 * круговой диаграмме соседние сектора соприкасаются.
 *
 * Семантические цвета (просрочено, оплачено) берутся из токенов и в
 * этот список не входят — они означают состояние, а не серию.
 */
/*
 * Одно холодное семейство — фиолетовый, синий, сланец — в трёх
 * светлотах, а не десять несвязанных оттенков. Прежний список был
 * радугой: изумрудный, янтарный, оранжевый и лаймовый стояли рядом с
 * акцентом, и диаграмма по должностям читалась как набор сигналов, а
 * не как один разрез. Хуже того, зелёный и янтарный в этой системе уже
 * заняты состояниями (успех, предупреждение), поэтому нейтральная
 * категория «Мастер по ремонту» выглядела успехом, а «Подменный
 * сотрудник» — предупреждением.
 *
 * Порядок чередует семейства, а не светлоты: на круговой диаграмме
 * соседние сектора соприкасаются, и подряд идущие оттенки одного тона
 * слились бы в пятно.
 */
export const CHART_PALETTE = [
  '#8b5cf6', // фиолетовый — ведущая серия
  '#3b82f6', // синий
  '#94a3b8', // сланец
  '#a78bfa', // светлый фиолетовый
  '#60a5fa', // светлый синий
  '#64748b', // тёмный сланец
  '#c4b5fd', // бледный фиолетовый
  '#93c5fd', // бледный синий
  '#cbd5e1', // светлый сланец
  '#0ea5e9', // голубой
];

export default CHART_PALETTE;
