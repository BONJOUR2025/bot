#!/usr/bin/env bash
# Проверка телефона перед взятием под управление БЕЗ заводского сброса.
#
# Зачем. Стать владельцем устройства на уже работающем телефоне можно, но
# Android ставит жёсткие условия, и главное из них — на аппарате не должно
# остаться НИ ОДНОГО аккаунта. «Вышли из Google» обычно недостаточно: свои
# аккаунты заводят фирменное облако (realme/Heytap, Mi, Samsung), WhatsApp и
# часть других приложений, и в настройках они не всегда лежат на виду.
#
# Скрипт только СМОТРИТ и ничего не меняет: его можно запускать сколько угодно
# раз, в том числе чтобы убедиться, что после чистки аккаунтов стало можно.
#
# Запуск (из Git Bash):
#   bash /c/deploy/bot-repo/device/mdm_agent/preflight.sh
#
# Взять телефон под управление — соседний adopt.sh (он же выключает
# Play Защиту, которая по воздуху не гасится).
set -u

ADB="${ADB:-/c/deploy/platform-tools/adb.exe}"
PKG="pw.bonjour.mdm"
ADMIN="$PKG/$PKG.AdminReceiver"

if [ ! -x "$ADB" ] && ! command -v "$ADB" >/dev/null 2>&1; then
  echo "adb не найден: $ADB"
  echo "Укажите путь: ADB=/путь/к/adb.exe bash $0"
  exit 1
fi

count_devices() { "$ADB" devices | sed -n '2,$p' | grep -c "device$"; }

echo "=== Телефон ==="
n=$(count_devices)
if [ "$n" -eq 0 ]; then
  echo "  НЕ ГОТОВО: телефон не виден по adb."
  echo "  Включите «Отладка по USB» в параметрах разработчика и разрешите"
  echo "  подключение с этого компьютера (запрос появится на экране телефона)."
  exit 1
fi
if [ "$n" -gt 1 ]; then
  echo "  НЕ ГОТОВО: подключено несколько устройств — оставьте одно."
  exit 1
fi

model=$("$ADB" shell getprop ro.product.model 2>/dev/null | tr -d '\r')
android=$("$ADB" shell getprop ro.build.version.release 2>/dev/null | tr -d '\r')
brand=$("$ADB" shell getprop ro.product.brand 2>/dev/null | tr -d '\r')
echo "  $brand $model, Android $android"

ready=0

# Xiaomi и родня: там дело не в аккаунтах, и выяснять это по месту дорого.
# Проверено на Redmi 2409BRN2CY (HyperOS 3, Android 16): shell-у запрещены любые
# операции с администраторами устройства — `dpm set-active-admin` отвечает
# SecurityException «Calling identity is not authorized» ещё до всякой проверки
# аккаунтов. Открывается это переключателем «Отладка по USB (Настройки
# безопасности)», а он требует входа в Mi-аккаунт.
case "$(echo "$brand" | tr 'A-Z' 'a-z')" in
  xiaomi|redmi|poco)
    cat <<'EOF'

  ВНИМАНИЕ, прошивка Xiaomi. Здесь мало убрать аккаунты — нужны ещё два
  переключателя в «Для разработчиков»:
    · «Установка через USB» — иначе adb не поставит APK
      (обходится: положить APK на телефон и установить с самого телефона);
    · «Отладка по USB (Настройки безопасности)» — без неё dpm отказывает
      с «Calling identity is not authorized».
  Второй требует входа в Mi-аккаунт (после включения из него можно выйти,
  переключатель остаётся). И ещё одно, неочевидное: режим USB должен быть
  «Передача файлов» (mtp), а не только зарядка — иначе переключатель показан
  включённым, а прав нет. Порядок: войти в Mi-аккаунт → включить оба
  переключателя → режим USB «Передача файлов» → выйти из Mi-аккаунта →
  убрать остальные аккаунты → перезагрузить → брать под управление.
EOF
    ;;
esac

echo
echo "=== Аккаунты (главное препятствие) ==="
# Берём только строки, где `Account {` стоит в начале — это перечень аккаунтов
# пользователя. Ниже в том же выводе есть строки `Session: ... Account {...}`:
# это система опрашивает приложения, и одно и то же приложение попадает туда
# многократно. Считая их, скрипт показывал вчетверо больше аккаунтов, чем есть,
# и отправлял чистить уже удалённое.
accounts=$("$ADB" shell dumpsys account 2>/dev/null | tr -d '\r' \
  | grep -E '^[[:space:]]*Account \{' \
  | grep -o 'Account {name=[^}]*}' | sed 's/Account {name=//; s/}$//' | sort -u)
if [ -z "$accounts" ]; then
  echo "  ок: аккаунтов нет"
else
  ready=1
  echo "  НЕ ГОТОВО: на телефоне остались аккаунты —"
  echo "$accounts" | sed 's/^/    · /'
  echo "  Удалите их все: Настройки → Аккаунты. Фирменное облако телефона и"
  echo "  часть приложений заводят свои аккаунты, их тоже нужно убрать."
fi

echo
echo "=== Управление ==="
owners=$("$ADB" shell dpm list-owners 2>/dev/null | tr -d '\r')
case "$owners" in
  *"$PKG"*)
      echo "  уже наш агент — телефон под управлением, делать нечего"; ready=2 ;;
  *"Device owner"*|*"Profile owner"*)
      ready=1
      echo "  НЕ ГОТОВО: на телефоне уже есть владелец/владелец профиля:"
      echo "$owners" | sed 's/^/    /'
      echo "  Такой аппарат берётся только через заводской сброс." ;;
  *)  echo "  ок: владельца устройства нет" ;;
esac

# Через dumpsys, а не `dpm list-admins`: такой подкоманды нет (на Android 16
# точно), и dpm в ответ печатает свою справку — которую легко принять за список
# администраторов и напугать оператора на ровном месте.
admins=$("$ADB" shell dumpsys device_policy 2>/dev/null | tr -d '\r' \
  | sed -n '/Enabled Device Admins/,/^[[:space:]]*$/p' \
  | grep -oE '[A-Za-z0-9_]+(\.[A-Za-z0-9_]+)+/[A-Za-z0-9_.$]+' | sort -u | grep -v "^$PKG/")
# Себя из списка исключаем: наш агент обязан быть администратором, и совет его
# отключить сломал бы управление телефоном — ровно то, ради чего всё делалось.
if [ -n "$admins" ]; then
  echo "  внимание: есть активные администраторы устройства —"
  echo "$admins" | sed 's/^/    /'
  echo "  Их надо отключить: Настройки → Безопасность → Приложения-администраторы."
fi

echo
echo "=== Пользователи ==="
users=$("$ADB" shell pm list users 2>/dev/null | tr -d '\r' | grep -c 'UserInfo{')
if [ "$users" -le 1 ]; then
  echo "  ок: один пользователь"
else
  ready=1
  echo "  НЕ ГОТОВО: пользователей на телефоне $users — удалите лишних и гостя."
fi

echo
echo "=== Итог ==="
if [ "$ready" -eq 2 ]; then
  echo "  Телефон уже под нашим управлением."
  exit 0
fi
if [ "$ready" -eq 0 ]; then
  cat <<EOF
  ГОТОВ. Данные телефона при этом НЕ стираются — приложения, фотографии и
  настройки остаются на месте, уходят только аккаунты (их можно вернуть сразу
  после). Дальше:

    bash \$(dirname "\$0")/adopt.sh

  adopt.sh поставит агент, назначит владельцем устройства и выключит Play
  Защиту (по воздуху она не гасится, а без этого тихая установка приложений
  на телефон не поедет). Отказ ничего не ломает и не стирает: телефон
  останется как был, а в тексте ошибки будет причина.
EOF
else
  echo "  НЕ ГОТОВ — см. пункты выше. Пока они не устранены, брать телефон"
  echo "  под управление без заводского сброса не получится."
fi
