"""Приведение кода точки из клетки графика к каноническому виду.

График руководитель набирает в Excel руками, и один и тот же салон приходит
как «Ох», «ох», «ОХ», « Ох », а иногда и с латинской «O» вместо кириллической
«О» (раскладку не переключили — на глаз не отличить). Раньше код сравнивался
со справочником салонов байт в байт, и такая смена молча пропадала: не
попадала ни в расчёт ЗП, ни в «кто сегодня на точке».

Сопоставляем без учёта регистра, пробелов и латинских двойников кириллицы;
незнакомое значение (выходной, больничный, опечатка) возвращаем как было —
его по-прежнему ловит проверка «неизвестные коды» в расчёте зарплаты.
"""
from __future__ import annotations

from typing import Iterable

# Латинские буквы, неотличимые на глаз от кириллических.
_LATIN_TO_CYR = str.maketrans({
    "A": "А", "B": "В", "C": "С", "E": "Е", "H": "Н", "K": "К", "M": "М",
    "O": "О", "P": "Р", "T": "Т", "X": "Х", "Y": "У",
    "a": "а", "c": "с", "e": "е", "o": "о", "p": "р", "x": "х", "y": "у",
})


def code_key(raw: object) -> str:
    """Ключ сравнения: без пробелов, кириллицей, без регистра."""
    s = "".join(str(raw or "").split())
    return s.translate(_LATIN_TO_CYR).casefold()


def build_code_index(known: Iterable[str]) -> dict[str, str]:
    """{ключ сравнения: код как в справочнике}."""
    index: dict[str, str] = {}
    for code in known:
        if code:
            index.setdefault(code_key(code), code)
    return index


def canonical_code(raw: object, index: dict[str, str]) -> str:
    """Код из справочника, если клетка ему соответствует, иначе — как есть."""
    stripped = str(raw or "").strip()
    if not stripped:
        return ""
    return index.get(code_key(stripped), stripped)
